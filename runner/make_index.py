"""Generate notes/CODE_AND_LOGS.md: every source file with one line of what it does, and every
run with where its records live.

    python runner/make_index.py            # rewrite the index
    python runner/make_index.py --check    # fail if the committed index is stale (for CI)

Source lines come from the first sentence of each file's module docstring, so the index cannot
drift from the code without the docstring drifting too. Files with no docstring are listed as
undocumented, which is the point: they show up as work to do.
"""

import argparse
import ast
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

GROUPS = [
    ("runner/", "Episode runners, scorers and judge evaluation"),
    ("meta/cd_tthe/", "Test-time harness evolution: the loop, task adapters, label isolation"),
    ("meta/cd_tthe/agents/", "Circuit Decoding harnesses (seed and proposer-written)"),
    ("meta/cd_tthe/agents_sp/", "Situation Puzzles harnesses (seed and proposer-written)"),
    ("meta/cd_evolve/", "The earlier one-shot evolution loop"),
    ("stage0/", "Hypothesis space, oracle and synthetic policies"),
    ("baselines/", "External baselines adapted to our tasks"),
    ("engaging/", "Slurm scripts for the MIT ORCD cluster"),
    ("h100/", "Scripts and notes for the standalone H100"),
    ("envs/", "Task environments"),
    ("signal/", "Signal extraction"),
    ("policy/", "Policies"),
]


def first_sentence(path):
    """The first sentence of the module docstring, or None."""
    try:
        if path.suffix == ".py":
            doc = ast.get_docstring(ast.parse(path.read_text(errors="replace")))
        else:
            lines = [l for l in path.read_text(errors="replace").splitlines()[:12]
                     if l.startswith("#") and not l.startswith("#!") and not l.startswith("#SBATCH")]
            doc = " ".join(l.lstrip("# ").strip() for l in lines[:3]) or None
    except Exception:
        return None
    if not doc:
        return None
    s = " ".join(doc.split())
    for stop in (". ", "; "):
        if stop in s[:400]:
            s = s[: s.index(stop) + 1]
            break
    return s[:300].rstrip()


def tracked():
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout
    return sorted(Path(p) for p in out.split() if p.endswith((".py", ".sh", ".sbatch")))


def runs():
    """Every run directory, with what it holds and where the rest of it is."""
    rows = []
    for d in sorted(list((ROOT / "meta/cd_tthe/logs").glob("*")) +
                    list((ROOT / "meta/cd_evolve/logs").glob("*"))):
        if not d.is_dir():
            continue
        rel = d.relative_to(ROOT)
        have = [n for n in ("result.json", "scores.json", "opt_log.jsonl", "branch_lineage.jsonl",
                            "session_audits.jsonl", "config.json", "trajectory.png") if (d / n).exists()]
        n_cand = len(list((d / "proposal_cards").glob("*.json"))) if (d / "proposal_cards").is_dir() else 0
        n_sess = len(list((d / "claude_sessions").glob("*"))) if (d / "claude_sessions").is_dir() else 0
        n_trace = len(list((d / "traces").rglob("*.json"))) if (d / "traces").is_dir() else 0
        n_res = len(list((d / "results").glob("*.jsonl"))) if (d / "results").is_dir() else 0
        rows.append((str(rel), have, n_cand, n_sess, n_trace, n_res))
    return rows


def build():
    L = ["# Index of code and runs", "",
         "Generated by [`runner/make_index.py`](../runner/make_index.py); do not edit by hand.",
         "Each source file is listed with the first sentence of its module docstring, so this index",
         "cannot drift from the code without the docstring drifting too. The experiments themselves",
         "are in [`EXPERIMENTS_LOG.md`](EXPERIMENTS_LOG.md); this file answers the narrower question",
         "of *where is the code and where are the records*.", "", "## Code", ""]

    files = tracked()
    seen = set()
    for prefix, title in GROUPS:
        group = [f for f in files if str(f).startswith(prefix) and str(f) not in seen
                 and str(f.parent) + "/" == prefix]
        if not group:
            continue
        L += [f"### `{prefix}` — {title}", "", "| file | what it does |", "|---|---|"]
        for f in group:
            seen.add(str(f))
            d = first_sentence(ROOT / f) or "*(undocumented)*"
            L.append(f"| [`{f.name}`](../{f}) | {d} |")
        L.append("")
    rest = [f for f in files if str(f) not in seen]
    if rest:
        L += ["### Other tracked sources", "", "| file | what it does |", "|---|---|"]
        for f in rest:
            L.append(f"| [`{f}`](../{f}) | {first_sentence(ROOT / f) or '*(undocumented)*'} |")
        L.append("")

    L += ["## Runs and where their records live", "",
          "`result`/`scores` = aggregate score files (committed). `cards` = proposer proposal cards.",
          "`sessions` = proposer and judge transcripts. `traces` / `results` = per-episode records,",
          "which are **not committed** — they carry gold and ship in the GitHub Release tarballs.",
          "Controller-private records (solve jobs, full optimisation logs, lineage) live outside the",
          "repository in `~/.ar_harness_controller/<run>/` and are never committed.", "",
          "| run | committed files | cards | sessions | traces | result files |", "|---|---|---|---|---|---|"]
    for rel, have, nc, ns, nt, nr in runs():
        L.append(f"| `{rel}` | {', '.join(have) or '—'} | {nc or '—'} | {ns or '—'} | "
                 f"{nt or '—'} | {nr or '—'} |")
    L += ["", "## What is deliberately not in the repository", "",
          "| content | where it is | why |", "|---|---|---|",
          "| per-episode traces and evaluation records | Release `v0.1-experiments-2026-10-11` | they carry the gold answers |",
          "| controller-private records | `~/.ar_harness_controller/<run>/` | label isolation: the proposer must not be able to read them |",
          "| generated self-test scripts (`check_*.py`) | inside the run tarballs | one per candidate per round, a runtime product |",
          "| model-call caches (`solver_cache*/`) | local only | reproducible from the records, large and uninteresting |",
          "| third-party checkouts, papers | pinned in `THIRD_PARTY.md`, ids in `RELATED_WORK.md` | not ours to redistribute |",
          "| credentials | macOS keychain | never in the repository, in any form |", ""]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    out = ROOT / "notes/CODE_AND_LOGS.md"
    new = build()
    if a.check:
        old = out.read_text() if out.exists() else ""
        if old != new:
            sys.exit("notes/CODE_AND_LOGS.md is stale; run python runner/make_index.py")
        print("index is current")
        return
    out.write_text(new)
    n_files = new.count("](../")
    print(f"wrote {out.relative_to(ROOT)}  ({n_files} links, {new.count(chr(10))+1} lines)")
    undoc = new.count("*(undocumented)*")
    if undoc:
        print(f"{undoc} files have no module docstring")


if __name__ == "__main__":
    main()
